import '@testing-library/jest-dom/vitest';

// jsdom does not provide a real localStorage implementation when running under
// Node/Vitest without --localstorage-file. Polyfill it with an in-memory store
// so tests that rely on localStorage (e.g. resumeStorage, App) work correctly.
const localStorageMock = (() => {
  let store: Record<string, string> = {};
  return {
    getItem: (key: string) => store[key] ?? null,
    setItem: (key: string, value: string) => {
      store[key] = value;
    },
    removeItem: (key: string) => {
      delete store[key];
    },
    clear: () => {
      store = {};
    },
    get length() {
      return Object.keys(store).length;
    },
    key: (index: number) => Object.keys(store)[index] ?? null,
  };
})();

Object.defineProperty(globalThis, 'localStorage', {
  value: localStorageMock,
  writable: true,
});
